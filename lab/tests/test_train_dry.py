TOOLS = [{"type": "function", "function": {"name": "set_fields", "description": "Write field values.",
                                            "parameters": {"type": "object", "properties": {}}}}]


def a_row(rid: str, with_history: bool = False) -> dict:
    call = trainkit.render_tool_call("toolu_01", "set_fields",
                                     {"target": {"kind": "section", "page": "home", "sectionId": "heroBanner"},
                                      "values": {"heading": "Fresh cookies, daily — café"}})
    messages = [{"role": "system", "content": "You are Sous Chef."}]
    if with_history:
        messages += [{"role": "user", "content": "earlier ask"}, {"role": "assistant", "content": "earlier reply"}]
    messages += [
        {"role": "user", "content": json.dumps({"page": "home"}) + "\nChange the hero heading"},
        {"role": "assistant", "content": "", "tool_calls": [call]},
        trainkit.render_tool_result("toolu_01", "set_fields", {"ok": True, "written": ["values.heading"]}),
        {"role": "assistant", "content": "Done — the hero heading now reads “Fresh cookies, daily — café”."},
    ]
    meta = {"model": "claude-fable-5-1", "kind": "set_field", "history_assistant_turns": 1 if with_history else 0}
    return {"id": rid, "messages": messages, "tools": TOOLS, "meta": meta}


def a_pair(pid: str) -> dict:
    row = a_row(pid)
    last = row["messages"][-1]
    return {"id": pid, "prompt": row["messages"][:-1], "chosen": [last],
            "rejected": [dict(last, content="I changed the footer instead.")], "tools": TOOLS,
            "meta": {"case_id": pid.split("#")[0], "type": "final", "kind": "set_field"}}


def write_jsonl(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8")



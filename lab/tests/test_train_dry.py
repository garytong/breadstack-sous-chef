def test_a_tool_call_is_rendered_in_the_thermometer_shape():
    # breadstack-thermometer/lab/in-house-model/lab/hf.py to_hf, lines 136-137:
    #   {"id": tid, "type": "function", "function": {"name": name, "arguments": json.dumps(args, ensure_ascii=False)}}
    args = {"target": {"kind": "global", "panel": "footer"}, "values": {"text": "© Café — “quotes”", "n": 3, "on": True}}
    thermometer = {"id": "toolu_9", "type": "function",
                   "function": {"name": "set_fields", "arguments": json.dumps(args, ensure_ascii=False)}}
    got = trainkit.render_tool_call("toolu_9", "set_fields", args)
    assert got == thermometer
    assert json.dumps(got, sort_keys=True) == json.dumps(thermometer, sort_keys=True)
    assert isinstance(got["function"]["arguments"], str) and "\\u" not in got["function"]["arguments"]
    assert trainkit.render_tool_call("t", "x", "not a dict")["function"]["arguments"] == "{}"
    assert trainkit.render_tool_result("toolu_9", "set_fields", {"ok": True}) == \
        {"role": "tool", "tool_call_id": "toolu_9", "name": "set_fields", "content": '{"ok": true}'}
    assert trainkit.hf_tool({"name": "a", "description": None}) == \
        {"type": "function", "function": {"name": "a", "description": "", "parameters": {"type": "object", "properties": {}}}}



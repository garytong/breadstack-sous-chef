def test_importing_the_modules_never_imports_torch():
    code = ("import sys; sys.path.insert(0, %r); import souschef_lab.trainkit, souschef_lab.train, souschef_lab.dpo, "
            "souschef_lab.export; heavy = sorted(m for m in sys.modules if m.split('.')[0] in "
            "('torch', 'unsloth', 'trl', 'transformers', 'datasets', 'peft')); print(heavy)") % str(LAB)
    r = subprocess.run([sys.executable, "-c", code], capture_output=True, text=True, check=True)
    assert r.stdout.strip() == "[]"
    assert "torch" not in sys.modules



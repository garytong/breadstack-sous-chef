def test_the_yaml_subset_parser():
    text = ("a: 1\nb: two words\nc:\n  d: true\n  e: ~\n  f: 'q'\ng:\n  - x\n  - 2\nh: [1, 2]\ni: 2.5  # note\n"
            "# a comment\n\"j\": null\n")

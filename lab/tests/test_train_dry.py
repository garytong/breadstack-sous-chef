def test_trained_spans_and_the_history_mask():
    inst, resp = trainkit.MARKERS["chatml"]
    text = (f"<|im_start|>system\nS<|im_end|>\n{inst}Q1<|im_end|>\n{resp}A1<|im_end|>\n{inst}Q2<|im_end|>\n"
            f"{resp}CALL<|im_end|>\n{inst}<tool_response>R</tool_response><|im_end|>\n{resp}A2<|im_end|>\n")
    assert trainkit.trained_spans(text, inst, resp) == ["A1<|im_end|>\n", "CALL<|im_end|>\n", "A2<|im_end|>\n"]
    assert trainkit.template_kind(text) == "chatml" and trainkit.template_kind("<start_of_turn>") is None
    row = {"messages": [{"role": "tool", "name": "set_fields", "content": "<tool_response>R</tool_response>"}]}
    assert trainkit.leaked_tool_results(row, text, inst, resp) == []
    leaky = text.replace(f"{inst}<tool_response>R</tool_response>", "<tool_response>R</tool_response>")
    assert trainkit.leaked_tool_results(row, leaky, inst, resp) == ["set_fields"]
    ids = [9, 1, 2, 5, 6, 3, 4, 7, 1, 2, 8, 3, 4, 10]  # resp = [1, 2], inst = [3, 4]
    labels = list(ids)
    masked = trainkit.mask_history_turns(ids, labels, [1, 2], [3, 4], 1)
    assert masked == [9, 1, 2, -100, -100, 3, 4, 7, 1, 2, 8, 3, 4, 10]
    assert trainkit.mask_history_turns(ids, labels, [1, 2], [3, 4], 0) == labels
    assert trainkit.find_all([1, 1, 1], [1, 1]) == [0] and trainkit.find_all([1], []) == []
    assert trainkit.weighted_loss([(1.0, 1), (3.0, 3), (9.0, 0)]) == 2.5 and trainkit.weighted_loss([]) is None
    assert trainkit.val_subset(list(range(10)), 3, 1) == trainkit.val_subset(list(range(10)), 3, 1)
    assert len(trainkit.val_subset(list(range(10)), 3, 1)) == 3 and trainkit.val_subset([1, 2], None, 1) == [1, 2]


